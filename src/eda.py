def eta_squared_kw(groups):
    # epsilon-like effect from Kruskal H
    all_vals = np.concatenate(groups); N = len(all_vals); k = len(groups)
    H, pv = stats.kruskal(*groups)
    eps2 = (H - k + 1) / (N - k) if N > k else np.nan
    return H, pv, eps2

cont_assoc = []
for c in corr_cols:
    groups = [lab.loc[y==g, c].dropna().values for g in sorted(y.unique())]
    groups = [g for g in groups if len(g) > 5]
    if len(groups) >= 2:
        try:
            H, pv, eps2 = eta_squared_kw(groups)
            cont_assoc.append((c, round(eps2,3), f"{pv:.1e}"))
        except Exception:
            pass
cont_df = pd.DataFrame(cont_assoc, columns=["feature","kruskal_eps2","p"]).sort_values("kruskal_eps2", ascending=False)
