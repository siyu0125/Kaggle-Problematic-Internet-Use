def cramers_v(x, yy):
    ct = pd.crosstab(x, yy)
    chi2 = stats.chi2_contingency(ct)[0]
    n = ct.values.sum(); r, k = ct.shape
    return np.sqrt(chi2 / (n * (min(r, k) - 1))) if min(r,k) > 1 else np.nan

